//! Host classes: Rust structs exposed to JavaScript with a constructor and
//! methods, built on the engine interface's host objects (ADR 0006).

use crate::error::{Error, JsError, Result};
use crate::{convert, throw, Context};
use agnijs_engine_api::{CallContext, Engine, HostClassDef, HostObject, PropertyKey, Value};
use serde_json::Value as Json;
use std::any::TypeId;
use std::rc::Rc;

/// A Rust type usable as a JavaScript class. Derive it with
/// `#[derive(agnijs::HostClass)]`.
pub trait HostClass: HostObject + Sized {
    /// The JavaScript class name (the global the constructor is bound to).
    const NAME: &'static str;
}

/// The constructor and methods of a [`HostClass`]. Generated by
/// `#[agnijs::host_methods]` on an `impl` block; implement it by hand only
/// when the macro does not fit.
pub trait HostClassMethods: HostClass {
    fn build(builder: &mut ClassBuilder<Self>);
}

type CtorFn<T> = Box<dyn Fn(&[Json]) -> std::result::Result<T, JsError>>;
type MethodFn<T> = Rc<dyn Fn(&mut T, &[Json]) -> std::result::Result<Option<Json>, JsError>>;

/// Collects a class's constructor and methods; see [`HostClassMethods`].
pub struct ClassBuilder<T> {
    ctor: Option<CtorFn<T>>,
    methods: Vec<(&'static str, MethodFn<T>)>,
}

impl<T> ClassBuilder<T> {
    /// Define the constructor (what `new Name(...)` runs).
    pub fn constructor(
        &mut self,
        f: impl Fn(&[Json]) -> std::result::Result<T, JsError> + 'static,
    ) -> &mut Self {
        self.ctor = Some(Box::new(f));
        self
    }
    /// Add a method to the prototype. `None` returns `undefined`.
    pub fn method(
        &mut self,
        name: &'static str,
        f: impl Fn(&mut T, &[Json]) -> std::result::Result<Option<Json>, JsError> + 'static,
    ) -> &mut Self {
        self.methods.push((name, Rc::new(f)));
        self
    }
}

fn valid_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c.is_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_alphanumeric() || c == '_' || c == '$')
}

fn json_args(engine: &mut dyn Engine, cx: &CallContext) -> std::result::Result<Vec<Json>, JsError> {
    cx.args
        .iter()
        .map(|a| convert::js_to_json(engine, cx.realm, a))
        .collect::<Result<Vec<_>>>()
        .map_err(|e| JsError::type_error(e.to_string()))
}

fn ret_to_js(
    engine: &mut dyn Engine,
    cx: &CallContext,
    r: Option<Json>,
) -> agnijs_engine_api::Result<Value> {
    match r {
        None => Ok(Value::Undefined),
        Some(j) => convert::json_to_js(engine, cx.realm, &j).map_err(|e| match e {
            Error::Engine(e) => e,
            other => throw(engine, cx.realm, &JsError::type_error(other.to_string())),
        }),
    }
}

impl Context {
    /// Register a host class: bind its constructor to a global of the class
    /// name and give instances the methods from [`HostClassMethods`].
    ///
    /// The JavaScript side is a real `class`, so calling it without `new`
    /// throws, `instanceof` works and scripts can subclass it. A method
    /// called on a value that is not an instance throws a `TypeError`.
    pub fn register_class<T: HostClassMethods>(&mut self) -> Result<()> {
        if !valid_identifier(T::NAME) {
            return Err(Error::Convert(format!(
                "{:?} is not a valid JavaScript class name",
                T::NAME
            )));
        }
        let mut builder = ClassBuilder {
            ctor: None,
            methods: Vec::new(),
        };
        T::build(&mut builder);
        let realm = self.realm;
        let class = self.engine.register_host_class(HostClassDef {
            name: T::NAME.to_string(),
            finalize: None,
        });

        // Host functions are not constructors, so the class is a script
        // `class` whose constructor forwards to a host function that builds
        // the host object with the prototype of `new.target`.
        let ctor = builder.ctor;
        let create = self.engine.new_function(
            realm,
            T::NAME,
            Rc::new(move |engine: &mut dyn Engine, mut cx: CallContext| {
                let Some(ctor) = &ctor else {
                    let e = JsError::type_error(format!("{} is not constructible", T::NAME));
                    return Err(throw(engine, cx.realm, &e));
                };
                let proto = cx.args.remove(0);
                let args = json_args(engine, &cx).map_err(|e| throw(engine, cx.realm, &e))?;
                match ctor(&args) {
                    Ok(t) => engine.new_host_object(cx.realm, class, Box::new(t), Some(&proto)),
                    Err(e) => Err(throw(engine, cx.realm, &e)),
                }
            }),
        )?;
        let factory = self.engine.eval_script(
            realm,
            "<agnijs-class>",
            &format!(
                "(function (create) {{ return class {} {{ constructor(...args) {{ return create(new.target.prototype, ...args); }} }}; }})",
                T::NAME
            ),
        )?;
        let class_value = self
            .engine
            .call(realm, &factory, &Value::Undefined, &[create])?;
        let proto = self.engine.get(realm, &class_value, &"prototype".into())?;

        for (name, m) in builder.methods {
            let f = self.engine.new_function(
                realm,
                name,
                Rc::new(move |engine: &mut dyn Engine, cx: CallContext| {
                    let args = json_args(engine, &cx).map_err(|e| throw(engine, cx.realm, &e))?;
                    let wrong_receiver = || {
                        JsError::type_error(format!(
                            "method called on an incompatible receiver (expected {})",
                            T::NAME
                        ))
                    };
                    let result = match engine.host_object_data(&cx.this) {
                        Some(data) => match data.as_any_mut().downcast_mut::<T>() {
                            Some(t) => m(t, &args),
                            None => Err(wrong_receiver()),
                        },
                        None => Err(wrong_receiver()),
                    };
                    match result {
                        Ok(r) => ret_to_js(engine, &cx, r),
                        Err(e) => Err(throw(engine, cx.realm, &e)),
                    }
                }),
            )?;
            self.engine
                .set(realm, &proto, &PropertyKey::from(name), &f)?;
        }
        let global = self.engine.global_object(realm)?;
        self.engine
            .set(realm, &global, &PropertyKey::from(T::NAME), &class_value)?;
        self.classes.insert(TypeId::of::<T>(), (class, proto));
        Ok(())
    }

    /// Wrap a Rust value as an instance of its registered class.
    pub fn wrap<T: HostClassMethods>(&mut self, value: T) -> Result<Value> {
        let Some((class, proto)) = self.classes.get(&TypeId::of::<T>()).cloned() else {
            return Err(Error::Convert(format!(
                "class {} is not registered; call register_class first",
                T::NAME
            )));
        };
        Ok(self
            .engine
            .new_host_object(self.realm, class, Box::new(value), Some(&proto))?)
    }

    /// Borrow the Rust value inside an instance of `T`; `None` for any
    /// other value.
    pub fn host_object<T: HostClass>(&mut self, value: &Value) -> Option<&mut T> {
        self.engine
            .host_object_data(value)?
            .as_any_mut()
            .downcast_mut::<T>()
    }
}

#[doc(hidden)]
pub mod private {
    //! Support code for the macros. Not part of the public API.
    use super::*;
    use serde::{de::DeserializeOwned, Serialize};

    pub fn arg<T: DeserializeOwned>(args: &[Json], i: usize) -> std::result::Result<T, JsError> {
        let v = args.get(i).cloned().unwrap_or(Json::Null);
        serde_json::from_value(v).map_err(|e| JsError::type_error(format!("argument {i}: {e}")))
    }
    fn ser<T: Serialize>(t: T) -> std::result::Result<Option<Json>, JsError> {
        serde_json::to_value(t)
            .map(Some)
            .map_err(|e| JsError::type_error(e.to_string()))
    }
    pub fn ret_plain<T: Serialize>(t: T) -> std::result::Result<Option<Json>, JsError> {
        ser(t)
    }
    pub fn ret_result<T: Serialize, E: Into<JsError>>(
        r: std::result::Result<T, E>,
    ) -> std::result::Result<Option<Json>, JsError> {
        ser(r.map_err(Into::into)?)
    }
    pub fn ret_result_unit<E: Into<JsError>>(
        r: std::result::Result<(), E>,
    ) -> std::result::Result<Option<Json>, JsError> {
        r.map_err(Into::into)?;
        Ok(None)
    }
}

  AgnijsInterruptHook interrupt;
  AgnijsConsoleHook console;
  AgnijsResolveHook resolve_module;
  AgnijsLoadHook load_module;
  AgnijsImportMetaHook import_meta;
  AgnijsRejectionHook promise_rejection;
  AgnijsClockHook now_ms;

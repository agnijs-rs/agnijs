/*
 * AgniJS C API. See docs/c-api.md for the ownership, threading, reentrancy
 * and versioning rules. In short:
 *
 * - Every function returns an AgnijsStatus: 0 is success, positive values
 *   are outcomes of running JavaScript, negative values are errors in the
 *   call. agnijs_last_error() has the message.
 * - Everything the library hands out is a 64-bit id; 0 is never valid.
 *   Freed or foreign ids are reported, never dereferenced.
 * - An engine is used only on the thread that created it.
 * - No function panics or aborts; no allocation crosses the boundary.
 */

